/**
 * Packs the SQL migrations of the phone database into one TypeScript module. The app cannot
 * read files from disk at run time, so the SQL has to be part of the bundle; a plain module
 * needs no special Metro or Babel setup. Runs as a part of `pnpm db:generate`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const folder = fileURLToPath(new URL('../drizzle-sqlite', import.meta.url));
const target = fileURLToPath(new URL('../src/sqlite/migrations.generated.ts', import.meta.url));

interface Journal {
  entries: { idx: number; tag: string }[];
}

export function bundleMigrations(): string {
  const journal = JSON.parse(readFileSync(`${folder}/meta/_journal.json`, 'utf8')) as Journal;
  const migrations = Object.fromEntries(
    journal.entries.map((entry) => [
      `m${String(entry.idx).padStart(4, '0')}`,
      readFileSync(`${folder}/${entry.tag}.sql`, 'utf8').replace(/\r\n/g, '\n'),
    ]),
  );

  return [
    '// Generated by scripts/bundle-sqlite-migrations.ts from drizzle-sqlite/. Do not edit.',
    `export const journal = ${JSON.stringify(journal, null, 2)};`,
    '',
    `export const migrations: Record<string, string> = ${JSON.stringify(migrations, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(target, bundleMigrations());
  console.log(`Bundled the SQLite migrations into ${target}`);
}
